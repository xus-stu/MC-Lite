CHEERS = {cat: list(items) for cat, items in data_cheers.CHEERS.items()}
for (cat, idx), text in OVERRIDES.items():
    CHEERS[cat][idx - 1] = text

problems = []
all_texts = []
for cat in data_cheers.CATEGORY_ORDER:
    for i, text in enumerate(CHEERS[cat], 1):
        cjk = len(re.findall(r"[\u4e00-\u9fff]", text))
        if cjk < 25:
            problems.append(f"{cat}#{i} cjk={cjk}: {text}")
        if len(text) < 28:
            problems.append(f"{cat}#{i} len={len(text)}: {text}")
        all_texts.append(text)

if len(all_texts) != 300:
    problems.append(f"total={len(all_texts)}")
if len(set(all_texts)) != 300:
    problems.append("duplicate texts found")
if problems:
    print("\n".join(problems))
    raise SystemExit(1)

lines = [
    "# -*- coding: utf-8 -*-",
    '"""运动会加油稿文案：200米、1000米、跳绳各100则。"""',
    "",
    "CHEERS = {",
]
for cat in data_cheers.CATEGORY_ORDER:
    lines.append(f"    {json.dumps(cat, ensure_ascii=False)}: [")
    for text in CHEERS[cat]:
        lines.append(f"        {json.dumps(text, ensure_ascii=False)},")
    lines.append("    ],")
lines += ["}", "", f"CATEGORY_ORDER = {json.dumps(data_cheers.CATEGORY_ORDER, ensure_ascii=False)}", ""]

with open("data_cheers.py", "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))

print("ok: 300 items, min cjk =", min(len(re.findall(r"[\u4e00-\u9fff]", t)) for t in all_texts))
